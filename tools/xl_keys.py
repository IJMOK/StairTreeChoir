"""Build data/xlights-effects.json: the exact settings keys xLights reads, per effect.

    python -m tools.xl_keys <path to an xLights source checkout> [--tag 2026.18]

An effect's settings string is a list of KEY=value pairs, where KEY is a panel prefix
(E_ effect, B_ buffer, C_ colour, T_ blending/transitions), the control type
(SLIDER_, CHOICE_, CHECKBOX_, SPINCTRL_, TEXTCTRL_) and the property id. The property
ids and control types come from resources/effectmetadata/*.json; where the effect's
C++ reads a different spelling (On reads E_TEXTCTRL_Eff_On_Start, not E_SLIDER_), the
source wins. Keys that the source never names are marked unverified in the output.

Only the effects in EFFECTS are kept: the ones tools/fx.py uses. The output is
committed, so nothing here runs at show-building time.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from tools.tree_layout import ROOT

OUT = ROOT / "data" / "xlights-effects.json"
EFFECTS = ["On", "Faces", "ColorWash", "SingleStrand", "Marquee", "Twinkle", "Shimmer", "Meteors",
           "Shockwave", "Spirals", "Butterfly", "Fire", "Plasma", "Wave", "Strobe", "Pinwheel",
           "Galaxy", "Fan", "Bars", "Curtain", "Garlands", "Snowflakes", "Lightning", "Fill", "Circles"]
SHARED = {"Buffer": "B_", "Color": "C_", "Blending": "T_"}
# Panel keys the metadata leaves to custom UI rows; read by src-core/render/PixelBuffer.cpp.
EXTRA = {
    "Blending": {
        "Fadein": {"key": "T_TEXTCTRL_Fadein", "type": "float", "default": 0},
        "Fadeout": {"key": "T_TEXTCTRL_Fadeout", "type": "float", "default": 0},
        "In_Transition_Type": {"key": "T_CHOICE_In_Transition_Type", "type": "string", "default": "Fade"},
        "Out_Transition_Type": {"key": "T_CHOICE_Out_Transition_Type", "type": "string", "default": "Fade"},
        "LayerMethod": {"key": "T_CHOICE_LayerMethod", "type": "string", "default": "Normal",
                        "options": ["Normal", "Effect 1", "Effect 2", "1 is Mask", "2 is Mask", "1 reveals 2",
                                    "2 reveals 1", "Layered", "Highlight", "Highlight Vibrant", "Additive",
                                    "Subtractive", "Brightness", "Average", "Bottom-Top", "Left-Right", "Max", "Min"]},
        "EffectLayerMix": {"key": "T_SLIDER_EffectLayerMix", "type": "int", "default": 0},
    },
    "Color": {
        "SparkleFrequency": {"key": "C_SLIDER_SparkleFrequency", "type": "int", "default": 0},
        "MusicSparkles": {"key": "C_CHECKBOX_MusicSparkles", "type": "bool", "default": False},
    },
}
CONTROL = {"slider": "SLIDER", "checkbox": "CHECKBOX", "choice": "CHOICE", "spin": "SPINCTRL",
           "text": "TEXTCTRL", "textctrl": "TEXTCTRL", "radio": "CHOICE", "colour": "COLOURPICKER"}
NAMED = re.compile(r'"(?:E_)?((?:SLIDER|TEXTCTRL|CHOICE|CHECKBOX|SPINCTRL|VALUECURVE)_[A-Za-z0-9_]+)"')
CURVE = re.compile(r'GetValueCurve\w*\(\s*"([A-Za-z0-9_]+)"')


def effect_keys(meta: dict, source: str, prefix: str = "E_") -> dict:
    named = set(NAMED.findall(source))
    curves = set(CURVE.findall(source))
    keys = {}
    for p in meta.get("properties", []):
        if not isinstance(p, dict) or p.get("controlType") in (None, "custom", "label", "button"):
            continue
        pid, ct = p["id"], p["controlType"]
        found = [n for n in named if n.split("_", 1)[1] == pid and not n.startswith("VALUECURVE")]
        if found:
            key, verified = prefix + sorted(found)[0], True
        elif pid in curves:
            key, verified = f"{prefix}SLIDER_{pid}", True
        else:
            key, verified = f"{prefix}{CONTROL.get(ct, ct.upper())}_{pid}", False
        entry = {"key": key, "type": p.get("type"), "default": p.get("default")}
        for k in ("min", "max", "options", "divisor"):
            if k in p:
                entry[k] = p[k]
        if not verified:
            entry["unverified"] = True
        keys[pid] = entry
    return keys


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("source", type=Path)
    ap.add_argument("--tag", default="2026.18")
    args = ap.parse_args(argv)
    meta_dir = args.source / "resources" / "effectmetadata"
    out = {"_comment": f"Generated by tools/xl_keys.py from xLights {args.tag} (effect metadata + effect source). Don't edit.",
           "effects": {}, "shared": {}}
    for name in EFFECTS:
        meta = json.loads((meta_dir / f"{name}.json").read_text(encoding="utf-8"))
        src = (args.source / "src-core" / "effects" / f"{name}Effect.cpp").read_text(encoding="utf-8", errors="replace")
        out["effects"][name] = effect_keys(meta, src)
    for name, prefix in SHARED.items():
        meta = json.loads((meta_dir / "shared" / f"{name}.json").read_text(encoding="utf-8"))
        out["shared"][name] = effect_keys(meta, "", prefix) | EXTRA.get(name, {})
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    n = sum(len(v) for v in out["effects"].values())
    u = sum(1 for v in out["effects"].values() for e in v.values() if e.get("unverified"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(EFFECTS)} effects, {n} keys ({u} not named in the source)")


if __name__ == "__main__":
    main()
