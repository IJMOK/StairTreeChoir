"""Site wiring from data/sites.json: electronics/site-wiring.md and electronics/<site id>.svg.

Power at each site (CLAUDE.md §4, Rob 26 Oct 2026): one enclosed Mean Well LRS PSU per
site, inside the site box (a DRiBOX Large), sized to the site's trees; every tree has
its own 12V run from the site box, fused 3A in its blade fuse box. The show player (Pi + amp)
and the site router are on their own fuses. Flex is 0.75mm² unless the voltage drop at the tree's limit needs more.

Each tree's WLED brightness limiter caps its pixels at TREE_LIMIT_A (gen_site_config.py
writes it), so a PSU is never overloaded whatever a sequence does. Full white
unlimited would be TREE_FULL_A.
"""

from __future__ import annotations

import json
from html import escape
from pathlib import Path

from tools.tree_layout import ROOT

SITES_FILE = ROOT / "data" / "sites.json"
MD_FILE = ROOT / "electronics" / "site-wiring.md"
SVG_DIR = ROOT / "electronics"

PIXELS = 92
PIXEL_W = 0.3                       # 12V WS2811 bullet at full white
VOLTS = 12.0
TREE_FULL_A = PIXELS * PIXEL_W / VOLTS   # 2.3A, every pixel full white
TREE_LIMIT_A = 2.0                  # WLED brightness limiter, per tree (pixels only)
TREE_A = TREE_LIMIT_A + 0.1         # + the ESP32 and its buck
PLAYER_A = 1.5                      # Pi + USB sound card + PAM8610 at show volume, at 12V
ROUTER_A = 1.0                      # Cudy WR3000 (12V 1A adapter), on the site PSU unless the site's "router" is "indoors"
PSUS = [("LRS-100-12", 8.5), ("LRS-150-12", 12.5), ("LRS-200-12", 17.0)]   # Mean Well, enclosed, fanless
PSU_MAX_LOAD = 0.9                  # the smallest PSU that carries the site at no more than 90% (all white)
FUSE_A = 3                          # every tree: 2.3A even unlimited; under the bayonet's ~4A (Rob, 26 Oct 2026)
PLAYER_FUSE_A = 3
ROUTER_FUSE_A = 2
COPPER = 0.0175                     # ohm mm²/m, copper at ~25°C
FLEX = (0.75, 1.5, 2.5)             # mm², 2-core outdoor flex
MAX_DROP = 0.8                      # volts lost on a run (out and back) before going up a size
SPARE = 1.1                         # buy 10% more flex than the runs add up to


def ip(tree: int) -> str:
    return f"192.168.8.{100 + tree}"


def drop(run_m: float, mm2: float, amps: float = TREE_A) -> float:
    return amps * 2 * run_m * COPPER / mm2


def flex_for(run_m: float) -> float:
    for mm2 in FLEX:
        if drop(run_m, mm2) <= MAX_DROP:
            return mm2
    raise ValueError(f"a {run_m}m run drops more than {MAX_DROP}V even on {FLEX[-1]}mm²; move the site box")


def load_sites(path: Path = SITES_FILE) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    seen = set()
    for site in data["sites"]:
        slots = [t["slot"] for t in site["trees"]]
        if slots != list(range(1, len(slots) + 1)) or len(slots) > 6:
            raise ValueError(f"{site['id']}: slots must be 1..n (n <= 6), got {slots}")
        for t in site["trees"]:
            if t["tree"] in seen or not 1 <= t["tree"] <= 14:
                raise ValueError(f"{site['id']}: tree {t['tree']} repeated or out of range")
            seen.add(t["tree"])
    return data


def psu_for(amps: float) -> tuple[str, float]:
    for name, rating in PSUS:
        if amps <= rating * PSU_MAX_LOAD:
            return name, rating
    raise ValueError(f"{amps:.1f}A is more than an {PSUS[-1][0]} should carry; split the site")


def plan(site: dict) -> dict:
    """The PSU, runs and their sizes for one site."""
    runs = []
    for t in site["trees"]:
        mm2 = flex_for(t["run_m"])
        d = drop(t["run_m"], mm2)
        runs.append({**t, "ip": ip(t["tree"]), "mm2": mm2, "drop": d, "v_tree": VOLTS - d})
    router_on_psu = site.get("router", "psu") != "indoors"
    amps = len(runs) * TREE_A + PLAYER_A + (ROUTER_A if router_on_psu else 0)
    name, rating = psu_for(amps)
    return {"site": site, "runs": runs, "router_on_psu": router_on_psu,
            "psu": {"name": name, "rating": rating, "amps": amps}}


def totals(plans: list[dict]) -> dict:
    flex: dict[float, float] = {}
    for p in plans:
        for r in p["runs"]:
            flex[r["mm2"]] = flex.get(r["mm2"], 0) + r["run_m"]
    return {
        "psus": {name: sum(p["psu"]["name"] == name for p in plans) for name, _ in PSUS},
        "fuses": sum(len(p["runs"]) for p in plans),
        "flex": {mm2: round(m * SPARE + 0.49) for mm2, m in sorted(flex.items())},
    }


def fmt_mm2(mm2: float) -> str:
    return f"{mm2:g}mm²"


def write_md(plans: list[dict], confirmed: bool, path: Path = MD_FILE) -> None:
    t = totals(plans)
    out = [
        "# Site wiring",
        "",
        "Generated by tools/gen_site_wiring.py from data/sites.json; don't edit.",
        "",
    ]
    if not confirmed:
        out += ["**Defaults, not yet confirmed by Rob:** tree counts per site and every run length. "
                "Edit data/sites.json and run `make all`.", ""]
    out += [
        "Each site: one enclosed Mean Well LRS PSU inside the site box (a DRiBOX Large), sized to the site; "
        f"each tree on its own run from the site box, fused {FUSE_A}A in a blade fuse box with a negative bus. "
        f"The show player (Pi, sound card, PAM8610) has its own {PLAYER_FUSE_A}A fuse and the router its own {ROUTER_FUSE_A}A. "
        f"Loads: {TREE_A:.1f}A per tree (WLED's brightness limiter holds the pixels to {TREE_LIMIT_A:g}A; "
        f"full white unlimited would be {TREE_FULL_A:.1f}A), {PLAYER_A}A for the player, {ROUTER_A}A for the router. "
        f"The PSU is the smallest that carries the site at no more than {PSU_MAX_LOAD:.0%}.",
        "",
        "The PSU's mains terminals sit under a printed cover; its mains lead comes in through a cord grip "
        "and plugs into an RCD-protected outdoor socket (or a weatherproof socket box on one).",
        "",
    ]
    for p in plans:
        s = p["site"]
        out += [f"## {s['name']} ({len(p['runs'])} trees, player {s['player']})", "",
                f"![{s['name']} wiring]({s['id']}.svg)", "",
                f"PSU: Mean Well {p['psu']['name']}, {p['psu']['amps']:.1f}A of {p['psu']['rating']:g}A "
                f"({p['psu']['amps'] / p['psu']['rating']:.0%}). "
                + (f"The router is on the PSU ({ROUTER_FUSE_A}A fuse)." if p["router_on_psu"]
                   else "The router is indoors on its own adapter, cabled to the Pi by Ethernet."), "",
                "| Slot | Tree | IP | Fuse | Run | Flex | Drop | At the tree |",
                "|---|---|---|---|---|---|---|---|"]
        for r in p["runs"]:
            out.append(f"| {r['slot']} | {r['tree']} (stairtree-{r['tree']:02d}) | {r['ip']} | {FUSE_A}A "
                       f"| {r['run_m']:g}m | {fmt_mm2(r['mm2'])} | {r['drop']:.2f}V | {r['v_tree']:.1f}V |")
        out.append("")
    out += ["## Shopping totals", "",
            *[f"- {n} × Mean Well {name}" for name, n in t["psus"].items() if n],
            f"- 1 spare Mean Well {PSUS[-1][0]} later: it covers any site",
            f"- {len(plans)} × blade fuse boxes with a negative bus (10-way); {t['fuses'] + len(plans)} × 3A "
            f"and {sum(p['router_on_psu'] for p in plans)} × {ROUTER_FUSE_A}A blade fuses (plus spares)"]
    out += [f"- {m}m of 2-core {fmt_mm2(mm2)} outdoor flex (runs + 10%)" for mm2, m in t["flex"].items()]
    out.append(f"- {t['fuses']} × PY07 Z108 2-pin bayonet connector sets, one per run (plus spares): "
               "socket on the run, pins on the tree's pigtail, red to +")
    out.append("")
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")


def write_svg(p: dict, path: Path) -> None:
    runs = p["runs"]
    row = 56
    top = 70
    h = top + (len(runs) + 1) * row + 30       # row 0 is the player
    w = 820
    box_x, box_w = 230, 270
    tree_x = 640
    el = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
          'font-family="sans-serif" font-size="12">',
          f'<rect width="{w}" height="{h}" fill="white"/>',
          f'<text x="12" y="24" font-size="16" font-weight="bold">{escape(p["site"]["name"])}: 12V and network</text>']

    def ty(i: int) -> float:                    # i = row; trees are rows 1..n
        return top + i * row + row / 2

    # site box (it holds the PSU too)
    el.append(f'<rect x="{box_x - 165}" y="{top - 30}" width="{box_w + 165}" height="{h - top}" fill="#eef4fb" stroke="#36c" rx="6"/>')
    el.append(f'<text x="{box_x - 157}" y="{top - 14}" fill="#36c">site box (DRiBOX Large)</text>')
    # the PSU, inside the box on the left, feeding every fuse
    psu = p["psu"]
    y = (ty(0) + ty(len(runs))) / 2
    bus_x = box_x - 15
    el.append(f'<rect x="{box_x - 150}" y="{y - 20}" width="120" height="40" fill="#fff3e0" stroke="#c60" rx="4"/>')
    el.append(f'<text x="{box_x - 90}" y="{y - 3}" text-anchor="middle">{psu["name"]}</text>')
    el.append(f'<text x="{box_x - 90}" y="{y + 12}" text-anchor="middle" fill="#666">{psu["amps"]:.1f} / {psu["rating"]:g}A</text>')
    el.append(f'<line x1="20" y1="{y}" x2="{box_x - 150}" y2="{y}" stroke="#a00" stroke-width="2"/>')
    el.append(f'<text x="18" y="{y - 6}" fill="#a00" font-size="10">mains (plug lead, cord grip)</text>')
    el.append(f'<line x1="{box_x - 30}" y1="{y}" x2="{bus_x}" y2="{y}" stroke="#c00" stroke-width="2"/>')
    el.append(f'<line x1="{bus_x}" y1="{ty(0)}" x2="{bus_x}" y2="{ty(len(runs))}" stroke="#c00" stroke-width="2"/>')
    for i in range(len(runs) + 1):
        el.append(f'<line x1="{bus_x}" y1="{ty(i)}" x2="{box_x + 20}" y2="{ty(i)}" stroke="#c00" stroke-width="2"/>')
    # fuses and runs
    for i, r in enumerate(runs):
        y = ty(i + 1)
        el.append(f'<rect x="{box_x + 20}" y="{y - 9}" width="44" height="18" fill="#ffe" stroke="#333"/>')
        el.append(f'<text x="{box_x + 42}" y="{y + 4}" text-anchor="middle">{FUSE_A}A</text>')
        el.append(f'<line x1="{box_x + 64}" y1="{y}" x2="{tree_x}" y2="{y}" stroke="#c00" stroke-width="2"/>')
        el.append(f'<text x="{box_x + box_w + 20}" y="{y - 6}">{r["run_m"]:g}m {fmt_mm2(r["mm2"])}, -{r["drop"]:.2f}V</text>')
        el.append(f'<rect x="{tree_x}" y="{y - 20}" width="160" height="40" fill="#e8f5e9" stroke="#2a7" rx="4"/>')
        el.append(f'<text x="{tree_x + 80}" y="{y - 3}" text-anchor="middle">tree {r["tree"]} · slot {r["slot"]}</text>')
        el.append(f'<text x="{tree_x + 80}" y="{y + 12}" text-anchor="middle" fill="#666">{r["ip"]}</text>')
    # player: row 0, inside the box, on its own fuse
    y = ty(0)
    el.append(f'<rect x="{box_x + 20}" y="{y - 9}" width="44" height="18" fill="#ffe" stroke="#333"/>')
    el.append(f'<text x="{box_x + 42}" y="{y + 4}" text-anchor="middle">{PLAYER_FUSE_A}A</text>')
    el.append(f'<line x1="{box_x + 64}" y1="{y}" x2="{box_x + 84}" y2="{y}" stroke="#c00" stroke-width="2"/>')
    el.append(f'<rect x="{box_x + 84}" y="{y - 22}" width="156" height="44" fill="white" stroke="#36c" rx="4"/>')
    el.append(f'<text x="{box_x + 162}" y="{y - 6}" text-anchor="middle">{escape(p["site"]["player"])} + FPP, router</text>')
    el.append(f'<text x="{box_x + 162}" y="{y + 10}" text-anchor="middle" fill="#666" font-size="10">5V buck · sound card · amp</text>')
    el.append(f'<line x1="{box_x + 240}" y1="{y}" x2="{tree_x}" y2="{y}" stroke="#555" stroke-dasharray="6 3"/>')
    el.append(f'<text x="{box_x + box_w + 20}" y="{y - 6}" fill="#555">speaker cable</text>')
    el.append(f'<rect x="{tree_x}" y="{y - 16}" width="160" height="32" fill="#f4f4f4" stroke="#555" rx="4"/>')
    el.append(f'<text x="{tree_x + 80}" y="{y + 4}" text-anchor="middle">speaker</text>')
    el.append(f'<text x="12" y="{h - 14}" fill="#36c" font-size="11">Trees get their frames over Wi-Fi from the site router (DDP); only 12V is wired.</text>')
    el.append("</svg>")
    path.write_text("\n".join(el) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    data = load_sites()
    plans = [plan(s) for s in data["sites"]]
    write_md(plans, data.get("confirmed", False))
    for p in plans:
        write_svg(p, SVG_DIR / f"{p['site']['id']}.svg")
    print(f"wrote {MD_FILE.relative_to(ROOT)} and {len(plans)} site diagrams")


if __name__ == "__main__":
    main()
