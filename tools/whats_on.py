"""docs/whats-on.md: the season for neighbours, friends and a WhatsApp or Facebook post.

Written by tools/fpp_bundle.py next to docs/show-plan.md, from the same playlists and schedule
(tools/gen_site_config.py) and the rendered show lengths, so it can't drift from what the
players do. Plain words only: no playlist names, no tech. Don't edit the file; change this.
"""

from __future__ import annotations

import datetime
import re

from tools import gen_site_config as cfg

OUT_FILE = cfg.ROOT / "docs" / "whats-on.md"
TBC = " *(to confirm)*"
SONG_TITLES = {"Rockin Around the Christmas Tree": "Rockin' Around the Christmas Tree"}


def _d(iso: str) -> datetime.date:
    return datetime.date.fromisoformat(iso)


def _day(iso: str) -> str:
    d = _d(iso)
    return f"{d.strftime('%A')} {d.day} {d.strftime('%B')}"


def _clock(minutes: float) -> str:
    """Minutes after midnight -> "5pm", "11:15pm", "midnight", "12:30am"."""
    h, m = divmod(int(round(minutes)) % (24 * 60), 60)
    if (h, m) == (0, 0):
        return "midnight"
    suffix = "am" if h < 12 else "pm"
    h12 = h % 12 or 12
    return f"{h12}{suffix}" if m == 0 else f"{h12}:{m:02d}{suffix}"


def _list(items: list[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def _songs(playlist: str, pls: dict) -> list[str]:
    return [SONG_TITLES.get(s, s) for s in cfg.sequences_used(pls[playlist]) if s in cfg.SONGS]


def _minutes(names: list[str], lengths: dict[str, float]) -> str:
    mins = sorted({round(lengths[n] / 60) for n in names if n in lengths})
    if not mins:
        return ""
    return f"about {mins[0]} minutes" if len(mins) == 1 else f"about {mins[0]}-{mins[-1]} minutes"


def lengths_from_plan(text: str) -> dict[str, float]:
    """Playlist -> seconds, read back from docs/show-plan.md's schedule tables (for the test)."""
    out = {}
    for name, mm, ss in re.findall(r"^\| \d\d:\d\d:\d\d \| ([^|]+?) \| (\d+):(\d\d) \|", text, re.M):
        out[name] = int(mm) * 60 + int(ss)
    return out


def render(lengths: dict[str, float]) -> str:
    """The page. lengths: scheduled playlist name -> seconds (the rendered shows)."""
    pls = cfg.playlists()
    season_end = _d(cfg.SEASON_END)
    first, last_xmas = _d(cfg.SEASON_START), _d(cfg.NYE)
    saturdays = [first + datetime.timedelta(days=k) for k in range((last_xmas - first).days)
                 if (first + datetime.timedelta(days=k)).weekday() == 5]
    sat_names = _list([f"{d.day}" for d in saturdays]) + " December"
    show_len = _minutes([n for n in lengths if re.match(r"Show [ABC]( |$)", n)], lengths)   # every night's A/B/C
    special_len = _minutes([cfg.SAT_SPECIAL], lengths)
    hours = [_clock(h * 60) for h in cfg.SHOW_HOURS]
    night_end = _clock(cfg.NIGHT_END)
    nyd_hours = [_clock(h * 60) for h in cfg.NYD_HOURS]
    nye_shows = [_clock(h * 60) for h, _ in cfg.NYE_SHOWS]
    lines = [
        "# What's on: the Stair Tree Choir",
        "",
        "Generated by `python -m tools.fpp_bundle` from the show schedule (tools/whats_on.py), like "
        "[show-plan.md](show-plan.md); don't edit it, change the schedule and re-run.",
        "",
        "## To copy and paste",
        "",
        f"> The Stair Tree Choir is back! Six singing Christmas trees, every evening from {first.day} "
        f"{first.strftime('%B')} to {season_end.day} {season_end.strftime('%B')}{TBC}. Lights on at "
        f"{_clock(cfg.WAITING_FROM)}, shows at {_list([h.removesuffix('pm') for h in hours])}pm ({show_len}), "
        f"goodnight at {_clock(cfg.GOODNIGHT_AT)}.",
        f"> Saturday Specials at {_clock(18 * 60)} with every song, a midnight countdown on New Year's Eve, "
        f"and New Year's Day shows from {nyd_hours[0]}. Bring your friends (and your grandma)!",
        "",
        "## A normal night",
        "",
        "| When | What's happening |",
        "|---|---|",
        f"| {_clock(cfg.WAITING_FROM)} | Lights on. Between shows the trees muck about: waves, winks, games of catch, "
        "and Bramble nodding off. Every quarter of an hour they tell you when the next show is. |",
        f"| {_list(hours)} | **Shows**, {show_len} each: four songs, plus jokes and chat in between. |",
        f"| {_clock(cfg.GOODNIGHT_AT)} | **Goodnight**: the choir says goodnight and settles down. |",
        f"| after {_clock(cfg.GOODNIGHT_AT)} | The trees doze, yawn and giggle quietly, with the lights turned "
        f"down low. Lights out by {night_end}. |",
        "",
        "The trees also wake up with us in the mornings: yawning, stretching and watching everyone go off to "
        "work and school.",
        "",
        "## What's in each show",
        "",
        "Three different shows, so if you stay for more than one you'll see something new.",
        "",
        "| Show | Songs |",
        "|---|---|",
    ]
    by_set: dict[str, list[str]] = {}
    for h, letter in zip(cfg.SHOW_HOURS, cfg.SHOW_SETS):
        by_set.setdefault(letter, []).append(_clock(h * 60))
    for letter, times in by_set.items():
        lines.append(f"| The {_list([t.removesuffix('pm') for t in times])} o'clock show | "
                     f"{', '.join(_songs(f'Show {letter}', pls))} |")
    lines += [
        "",
        "## Special nights",
        "",
        "| Date | What's different |",
        "|---|---|",
        f"| Saturdays {sat_names} | At {_clock(17 * 60)} a short taster (two songs), then at {_clock(18 * 60)} the "
        f"**Saturday Special**: every Christmas song we know in one go ({special_len}). The other shows as normal. |",
        f"| {_day(cfg.VILLAGE_NIGHT)}: **Village Night** | The big one. At {_clock(18 * 60)} the **Village Special** "
        f"with every song; the {_clock(17 * 60)} and {_clock(19 * 60)} shows have auditions for new voices from the crowd. |",
        f"| {_day(cfg.XMAS_EVE)}: **Christmas Eve** | Santa phones in during every show. At {_clock(cfg.GOODNIGHT_AT)} "
        "the choir falls asleep one by one so he can come, and they stay asleep all night. |",
        f"| {_day(cfg.NYE)}: **New Year's Eve** | Shows at {_list(nye_shows)}, a late show at "
        f"{_clock(cfg.NYE_LATE_AT)} (Bramble swears he'll stay up), then the **midnight countdown** and Auld Lang Syne. "
        f"Lights out by {_clock(cfg.NYE_NIGHT_END)}. |",
        f"| {_day(cfg.NYD)}: **New Year's Day** | New Year shows every hour from {nyd_hours[0]} to {nyd_hours[-1]}: "
        f"{', '.join(_songs(cfg.NYD_SHOW, pls))}{TBC}. Then the choir says goodbye for the year at "
        f"{_clock(cfg.NYD_GOODNIGHT_AT)}. |",
        "",
        "## Meet the choir",
        "",
        "Left to right: **Holly** (the conductor, bossy), **Ivy** (agrees with Holly), **Noel** (the tenor, holds every "
        "note too long), **Jingle** (very excited), **Bramble** (very sleepy) and **Pip** (the smallest, terrible jokes). "
        "More about them: [backstory.md](backstory.md).",
        "",
        "## Still to confirm",
        "",
        f"- The season dates ({first.day} {first.strftime('%B')} to {season_end.day} {season_end.strftime('%B')}) "
        "are a placeholder until Rob confirms them.",
        "- The New Year's Day songs aren't picked yet.",
        "",
    ]
    return "\n".join(lines)


def write(lengths: dict[str, float]) -> str:
    text = render(lengths)
    OUT_FILE.write_text(text, encoding="utf-8", newline="\n")
    return text
